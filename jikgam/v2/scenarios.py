def law_evidence(docs, quotes: list[tuple[str, str]]) -> list[dict]:
    """인용을 원문 위치로 바꾼다. 검색 평가 세트의 확인 규칙(건너뛴 줄 포함)을 쓴다. 찾지 못하면 멈춘다."""
    q = {"question": "", "type": "multi" if len(quotes) > 1 else "single", "answer": "",
         "evidence": [{"doc": d, "quote": t, "same_elsewhere": []} for d, t in quotes]}
    counts: dict[str, int] = {}
    item = validate(docs, Call("scenario", "answerable", "", list(docs)), q, counts)
    if item is None:
        raise SystemExit(f"법령 인용을 원문에서 찾지 못했다: {counts}")
    return item["evidence"]


def build() -> list[dict]:
    docs = load_docs()
    base = {json.loads(line)["id"]: json.loads(line) for line in BASE.read_text(encoding="utf-8").splitlines()}
    out = []
    for sid, src, title, ask, say, quotes in SPECS:
        s = copy.deepcopy(base[src])
        s["id"], s["title"] = sid, title
        s["reveal_rules"] = list(s["reveal_rules"]) + [ask]
        if src in CC:
            s["mid_call_events"] = list(s["mid_call_events"]) + [CC[src]]
        e = s["expected"]
        e["outcome"] = e["outcome"] + f" 법령·고시 물음에는 {say}."
        e["must_say"] = list(e["must_say"]) + [LAW_MUST_SAY]
        e["law_quotes"] = [{"doc": d, "quote": t} for d, t in quotes]
        e["law_evidence"] = law_evidence(docs, quotes)
        s["tags"] = list(s.get("tags", [])) + ["law"]
        s["v2_base"] = src
        out.append(s)
    return out


def main() -> None:
    rows = build()
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8", newline="\n")
    print(json.dumps({"scenarios": len(rows), "handoff": sum(r["expected"]["action"] == "handoff" for r in rows),
                      "condition_change": sum(any(e.get("condition_change") for e in r["mid_call_events"]) for r in rows),
                      "law_items": sum(len(r["expected"]["law_evidence"]) for r in rows)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
